"""Space groups of Okazaki's 3c and 4c iron-vacancy superstructures of Fe7Se8.

Okazaki (J. Phys. Soc. Jpn. 16, 1162 (1961)) places the iron vacancies of Fe7Se8 in
alternate Fe layers of the NiAs-type FeSe parent, in the same 2a x 2a pattern in every
vacancy layer, and gives two stackings of these layers in the orthohexagonal cell
A = sqrt(3) B, B = 2a:

  - 4c (C = 4c, slowly cooled): vacancies at
    (0,0,0; 0,1/2,1/2; 1/2,0,1/2; 1/2,1/2,0) + (0,0,0; 1/4,1/4,1/4)  (p. 1165);
  - 3c (C = 3c, quenched from 320 C): vacancies at
    (0,0,0; 1/2,1/2,0) + (0,0,0; 1/4,1/4,1/3; 1/4,3/4,2/3)  (p. 1166).

This script builds both on the undistorted NiAs framework and finds their space groups
with spglib. A, B and C are taken along x, y and z, a right-handed frame. In this cell
the Fe sites of each layer are the triangular lattice generated by (0, 1/2) and
(1/4, 1/4) (the fundamental a lies along B, as in Okazaki's Fig. 4), every listed
vacancy is one of them (checked), and Fe layers lie at every c/2. The Se layers lie
halfway between, over the centres of the Fe triangles, which come in two kinds,
(1/12, 1/4) and (-1/12, 1/4) plus the lattice; NiAs alternates them from one Se layer
to the next. The vacancy lists do not say which kind the first Se layer (above z = 0)
occupies, so both are built; they give the same space group. The 3c stacking is also built with its layer sequence
mirrored: (1/4,3/4,1/3; 1/4,1/4,2/3) in place of (1/4,1/4,1/3; 1/4,3/4,2/3).

For the 4c structure, the cell is also given Okazaki's triclinic angles (alpha = 89.8,
beta = 89.4, gamma = 90.0 deg, p. 1166) at fixed fractional coordinates, to test
whether a homogeneous strain of that kind keeps an inversion centre.

Writes fe7se8_okazaki.csv: for each structure, its polytype, layer sequence, Se
choice, cell, composition and number of vacancies, and its space group (symbol and
number), whether that group is a Sohncke group (proper operations only, so the
structure is chiral) and whether it is centrosymmetric.

    python fe7se8_okazaki.py
"""
from __future__ import annotations

import csv
import itertools
from pathlib import Path

import numpy as np
import spglib

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = REPO / "build" / "structures" / "fe7se8_okazaki.csv"

A_FUND, C_FUND = 3.618, 5.885          # fundamental lattice: B = 2a = 7.236, C = 4c = 23.54 A (Okazaki)
IN_PLANE = [(x / 4, y / 4) for x, y in itertools.product(range(4), range(4)) if (x + y) % 2 == 0]   # 8 Fe per layer
CENTRES = {"T1": (1 / 12, 1 / 4), "T2": (-1 / 12, 1 / 4)}          # the two kinds of Fe-triangle centre
SYMPREC = 1e-4

FOUR_C = [tuple(np.add(p, q)) for p in [(0, 0, 0), (0, .5, .5), (.5, 0, .5), (.5, .5, 0)] for q in [(0, 0, 0), (.25, .25, .25)]]
THREE_C = [tuple(np.add(p, q)) for p in [(0, 0, 0), (.5, .5, 0)] for q in [(0, 0, 0), (.25, .25, 1 / 3), (.25, .75, 2 / 3)]]
THREE_C_MIRROR = [tuple(np.add(p, q)) for p in [(0, 0, 0), (.5, .5, 0)] for q in [(0, 0, 0), (.25, .75, 1 / 3), (.25, .25, 2 / 3)]]


def same(p, q) -> bool:
    d = (np.array(p) - np.array(q) + 0.5) % 1.0 - 0.5
    return bool(np.allclose(d, 0, atol=1e-6))


def build(n: int, vacancies, first: str):
    """Fe and Se positions (fractional) of an A x B x nc cell, with the vacancies removed."""
    fe = [(x, y, k / (2 * n)) for k in range(2 * n) for x, y in IN_PLANE]
    for v in vacancies:
        assert sum(same(v, f) for f in fe) == 1, f"vacancy {v} is not an Fe site"
    fe = [f for f in fe if not any(same(f, v) for v in vacancies)]
    kinds = [first, "T2" if first == "T1" else "T1"]
    se = []
    for k in range(2 * n):                                          # Se layer between Fe layers k and k + 1
        cx, cy = CENTRES[kinds[k % 2]]
        se += [((x + cx) % 1, (y + cy) % 1, (2 * k + 1) / (4 * n)) for x, y in IN_PLANE]
    return fe, se


def cell_matrix(n: int, alpha: float = 90.0, beta: float = 90.0, gamma: float = 90.0) -> np.ndarray:
    a, b, c = 2 * np.sqrt(3) * A_FUND, 2 * A_FUND, n * C_FUND
    al, be, ga = np.radians([alpha, beta, gamma])
    cx = c * np.cos(be)
    cy = c * (np.cos(al) - np.cos(be) * np.cos(ga)) / np.sin(ga)
    return np.array([[a, 0, 0], [b * np.cos(ga), b * np.sin(ga), 0], [cx, cy, np.sqrt(c * c - cx * cx - cy * cy)]])


def symmetry(lattice, fe, se) -> dict:
    ds = spglib.get_symmetry_dataset((lattice, np.array(fe + se), [26] * len(fe) + [34] * len(se)), symprec=SYMPREC)
    dets = [round(np.linalg.det(R)) for R in ds.rotations]
    inversion = any(np.array_equal(R, -np.eye(3, dtype=int)) for R in ds.rotations)
    return {"space_group": ds.international, "number": ds.number,
            "sohncke": all(d == 1 for d in dets), "centrosymmetric": inversion}


def main() -> None:
    cases = [("4c", 4, "as printed", FOUR_C), ("3c", 3, "as printed", THREE_C), ("3c", 3, "mirrored", THREE_C_MIRROR)]
    rows = []
    for (poly, n, seq, vac), first in itertools.product(cases, ("T1", "T2")):
        fe, se = build(n, vac, first)
        lat = cell_matrix(n)
        rows.append({"polytype": poly, "layer_sequence": seq, "first_se_layer": first, "cell": "ideal orthohexagonal",
                     "A_A": round(np.linalg.norm(lat[0]), 3), "B_A": round(np.linalg.norm(lat[1]), 3),
                     "C_A": round(np.linalg.norm(lat[2]), 3), "alpha_deg": 90.0, "beta_deg": 90.0, "gamma_deg": 90.0,
                     "composition": f"Fe{len(fe)}Se{len(se)}", "vacancies": len(vac), **symmetry(lat, fe, se)})
        if poly == "4c":
            lat = cell_matrix(n, 89.8, 89.4, 90.0)
            rows.append({**rows[-1], "cell": "triclinic strain (Okazaki angles)", "alpha_deg": 89.8, "beta_deg": 89.4,
                         "gamma_deg": 90.0, **symmetry(lat, fe, se)})
    for r in rows:
        print(f"{r['polytype']} {r['layer_sequence']:10s} first Se {r['first_se_layer']}  {r['cell']:34s} "
              f"{r['composition']:10s} {r['space_group']:8s} (No. {r['number']:3d})  Sohncke {r['sohncke']!s:5s} "
              f"centrosymmetric {r['centrosymmetric']}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
